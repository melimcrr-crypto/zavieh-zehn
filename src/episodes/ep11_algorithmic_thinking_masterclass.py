def _get_chapter_bounds(tc: dict, sub_lines: list[dict], total_dur: float) -> list[float]:
    def t_seg(idx: int, fb: float) -> float:
        if idx < len(sub_lines):
            return float(sub_lines[idx]["start"])
        return fb

    s_end_vo = float(sub_lines[-1]["end"]) + 0.35 if sub_lines else (total_dur - 3.8)
    bounds = [0.0]
    for k, seg_i in enumerate(CHAPTER_START_INDICES[1:], start=1):
        bounds.append(t_seg(seg_i, k * 39.0))
    bounds.append(min(total_dur - 3.4, s_end_vo))  # B[14]: S15 Sapphire Pill CTA
    bounds.append(total_dur + 0.2)
    return bounds


